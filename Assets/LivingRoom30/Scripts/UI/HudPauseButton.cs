using UnityEngine;
using UnityEngine.UI;

namespace LivingRoom30
{
    [DisallowMultipleComponent]
    [RequireComponent(typeof(Button))]
    public sealed class HudPauseButton : MonoBehaviour
    {
        [SerializeField] private StopwatchHud stopwatch;
        [SerializeField] private Text label;
        [SerializeField] private string runningText = "PAUSE";
        [SerializeField] private string pausedText = "RESUME";

        public StopwatchHud Stopwatch => stopwatch;
        public Text Label => label;

        // Subscribing at runtime instead of through a persistent onClick listener: the scene is
        // generated by SceneNewBuilder, and runtime listeners are the ones that survive that path.
        private void Awake()
        {
            Button button = GetComponent<Button>();
            button.onClick.AddListener(Toggle);
            RefreshLabel();
        }

        public void Configure(StopwatchHud stopwatchHud, Text buttonLabel)
        {
            stopwatch = stopwatchHud;
            label = buttonLabel;
            RefreshLabel();
        }

        public void Toggle()
        {
            if (stopwatch == null)
            {
                return;
            }

            stopwatch.SetRunning(!stopwatch.IsRunning);
            RefreshLabel();
        }

        private void RefreshLabel()
        {
            if (label == null || stopwatch == null)
            {
                return;
            }

            label.text = stopwatch.IsRunning ? runningText : pausedText;
        }
    }
}
